"""Make the clean personal link, the forwarding page and the QR code for every advisor in js/advisors-data.js

Run from the repo root:
    pip install "qrcode[pil]"
    python scripts/make_advisor_links.py

What the client sees:   https://www.eawishlist.com/mohammed
It forwards to:         https://www.eawishlist.com/?a=mohammed&utm_source=advisor&utm_medium=whatsapp
                        &utm_campaign=personal-link&utm_content=mohammed#/      (the tags feed Google Analytics)

Output
  <id>/index.html    one small forwarding page per advisor  (COMMIT these - they are published)
  404.html           also forwards /Mohammed, /MOHAMMED ... (the web host is case-sensitive)  (COMMIT)
  advisor-qr/<id>.png + advisor-qr/links.csv   QR codes and the list of links (git-ignored, not published)
"""
import csv
import json
import pathlib
import re

import qrcode
from qrcode.constants import ERROR_CORRECT_M

BASE = "https://www.eawishlist.com/"
CAMPAIGN = "personal-link"  # utm_campaign: shows in Google Analytics (also set in advisors/links.html)
RESERVED = {"advisors", "advisor-qr", "assets", "contact", "css", "data", "firebase", "js", "print", "qr", "scripts", "index", "404"}

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "js" / "advisors-data.js").read_text(encoding="utf-8")
advisors = json.loads(re.search(r"EA_ADVISORS\s*=\s*(\[.*?\])\s*;", src, re.S).group(1))

for a in advisors:
    if not re.fullmatch(r"[a-z0-9]+", a["id"]) or a["id"] in RESERVED:
        raise SystemExit(f"Advisor id '{a['id']}' must be lowercase letters/numbers and not clash with a site folder.")


def target(a):
    # The query string goes BEFORE the # so the site's hash links still work.
    return (f"/?a={a['id']}&utm_source=advisor&utm_medium=whatsapp"
            f"&utm_campaign={CAMPAIGN}&utm_content={a['id']}#/")


HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Emporio Armani — Marassi Mall, Bahrain</title>
<!-- Generated by scripts/make_advisor_links.py - do not edit by hand. -->
<meta property="og:type" content="website">
<meta property="og:site_name" content="Emporio Armani Bahrain">
<meta property="og:title" content="Emporio Armani — Marassi Mall, Bahrain">
<meta property="og:description" content="Browse the FW26 selection and send us your favourite pieces on WhatsApp.">
<meta property="og:url" content="%(url)s">
<meta property="og:image" content="https://www.eawishlist.com/assets/og-image.jpg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
"""

PAGE = HEAD + """<script>location.replace(%(js)s);</script>
<meta http-equiv="refresh" content="0; url=%(target)s">
</head>
<body style="font-family:Arial,sans-serif;text-align:center;padding:40px">
  <a href="%(target)s">Emporio Armani Marassi</a>
</body>
</html>
"""

# /Mohammed, /MOHAMMED ... : GitHub Pages is case-sensitive, so this page forwards them to the right advisor.
NOT_FOUND = HEAD + """<script src="/js/advisors-data.js"></script>
<script>
(function () {
  var seg = decodeURIComponent(location.pathname.split("/").filter(Boolean)[0] || "").toLowerCase().replace(/[^a-z0-9]/g, "");
  var list = window.EA_ADVISORS || [];
  for (var i = 0; i < list.length; i++) {
    if (list[i].id === seg) {
      location.replace("/?a=" + seg + "&utm_source=advisor&utm_medium=whatsapp&utm_campaign=%(campaign)s&utm_content=" + seg + "#/");
      return;
    }
  }
  document.addEventListener("DOMContentLoaded", function () { document.getElementById("nf").hidden = false; });
})();
</script>
</head>
<body style="font-family:Arial,sans-serif;text-align:center;padding:40px">
  <p id="nf" hidden>Page not found.<br><a href="/">Emporio Armani Marassi — browse the collection</a></p>
</body>
</html>
"""

out = root / "advisor-qr"
out.mkdir(exist_ok=True)

rows = []
for a in advisors:
    clean = f"{BASE}{a['id']}"
    folder = root / a["id"]
    folder.mkdir(exist_ok=True)
    (folder / "index.html").write_text(
        PAGE % {"url": clean, "js": json.dumps(target(a)), "target": target(a).replace("&", "&amp;")}, encoding="utf-8")

    qr = qrcode.QRCode(error_correction=ERROR_CORRECT_M, box_size=12, border=4)
    qr.add_data(clean)
    qr.make(fit=True)
    qr.make_image(fill_color="black", back_color="white").save(out / f"{a['id']}.png")
    rows.append([a["id"], a["name"], clean])
    print(a["name"], "->", clean)

(root / "404.html").write_text(NOT_FOUND % {"url": BASE, "campaign": CAMPAIGN}, encoding="utf-8")

with open(out / "links.csv", "w", newline="", encoding="utf-8-sig") as f:
    csv.writer(f).writerows([["id", "name", "link"]] + rows)
